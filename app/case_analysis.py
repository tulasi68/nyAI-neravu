"""Conservative, source-traceable case-record analysis for synthetic demonstrations.

This is an extractive completeness/traceability aid, not legal reasoning,
legal research, fact-finding, credibility assessment, or an outcome predictor.
It deliberately does not choose a winner or infer that an allegation is true.
"""
from __future__ import annotations

import re
from collections import Counter
from typing import List, Optional, Set
from pydantic import BaseModel, Field, model_validator

_STOP_WORDS = {
    "the", "and", "for", "that", "this", "with", "from", "have", "has", "had",
    "was", "were", "are", "is", "not", "but", "into", "onto", "than", "then",
    "they", "them", "their", "there", "here", "when", "where", "which", "who",
    "what", "why", "how", "shall", "would", "could", "should", "may", "might",
    "must", "can", "will", "been", "being", "its", "our", "your", "his", "her",
    "under", "over", "between", "after", "before", "about", "against", "each",
    "both", "also", "any", "all", "some", "such", "other", "party", "case",
}
_NEGATION = {"not", "no", "never", "neither", "without", "denied", "dispute", "disputed", "false", "didn't", "cannot"}


def tokens(text: str) -> Set[str]:
    return {
        w for w in re.findall(r"[a-zA-Z0-9][a-zA-Z0-9'-]{1,}", text.lower())
        if w not in _STOP_WORDS and not w.isdigit()
    }


class RecordSource(BaseModel):
    reference: str = Field(min_length=1, max_length=120)
    description: str = Field(min_length=1, max_length=2000)
    text: str = Field(min_length=1, max_length=12000)
    page_or_location: Optional[str] = Field(None, max_length=120)
    source_type: str = Field(default="document", max_length=80)


class PartyPosition(BaseModel):
    party_label: str = Field(min_length=1, max_length=160)
    position: str = Field(min_length=1, max_length=6000)
    references: List[str] = Field(default_factory=list, max_length=50)


class RecordClaim(BaseModel):
    claim_id: str = Field(min_length=1, max_length=80)
    side: str = Field(min_length=1, max_length=160, description="Party label or neutral procedural claim")
    claim_text: str = Field(min_length=1, max_length=3000)
    cited_references: List[str] = Field(default_factory=list, max_length=50)


class AnalysisRequest(BaseModel):
    synthetic_data_attestation: bool
    case_number: str = Field(min_length=1, max_length=120)
    case_category: str = Field(min_length=1, max_length=80)
    issues: List[str] = Field(min_length=1, max_length=30)
    sources: List[RecordSource] = Field(min_length=1, max_length=100)
    party_positions: List[PartyPosition] = Field(default_factory=list, max_length=30)
    claims: List[RecordClaim] = Field(default_factory=list, max_length=100)

    @model_validator(mode="after")
    def validate_synthetic_and_unique_sources(self):
        if not self.synthetic_data_attestation:
            raise ValueError("Only synthetic test records may be analysed by this prototype.")
        refs = [s.reference for s in self.sources]
        if len(refs) != len(set(refs)):
            raise ValueError("Source references must be unique.")
        ids = [c.claim_id for c in self.claims]
        if len(ids) != len(set(ids)):
            raise ValueError("Claim IDs must be unique.")
        return self


def analyze_record(req: AnalysisRequest) -> dict:
    source_map = {s.reference: s for s in req.sources}
    source_tokens = {ref: tokens(f"{s.description} {s.text}") for ref, s in source_map.items()}
    issue_results = []
    for issue in req.issues:
        issue_terms = tokens(issue)
        ranked = []
        for ref, src in source_map.items():
            overlap = issue_terms & source_tokens[ref]
            if overlap:
                ranked.append({
                    "reference": ref,
                    "description": src.description,
                    "page_or_location": src.page_or_location,
                    "matching_terms": sorted(overlap),
                    "overlap_count": len(overlap),
                    "review_note": "Lexical overlap only; this does not establish evidentiary support.",
                })
        ranked.sort(key=lambda x: (-x["overlap_count"], x["reference"]))
        issue_results.append({
            "issue": issue,
            "candidate_sources": ranked,
            "source_found": bool(ranked),
            "warning": "Candidate links are generated by word overlap, not legal or factual inference.",
        })

    claim_results = []
    for claim in req.claims:
        unknown = sorted(set(claim.cited_references) - set(source_map))
        cited_text_tokens = set().union(*(source_tokens[r] for r in claim.cited_references if r in source_map)) if claim.cited_references else set()
        claim_terms = tokens(claim.claim_text)
        overlap = sorted(claim_terms & cited_text_tokens)
        claim_results.append({
            "claim_id": claim.claim_id,
            "side": claim.side,
            "claim_text": claim.claim_text,
            "cited_references": claim.cited_references,
            "unknown_references": unknown,
            "textual_overlap_terms": overlap,
            "citation_traceability": "unknown_reference" if unknown else ("some_textual_overlap" if overlap else "no_textual_overlap_found"),
            "review_note": "Text overlap cannot verify truth, admissibility, authenticity, or whether the cited source fairly supports the claim.",
        })

    party_coverage = []
    for pos in req.party_positions:
        missing = sorted(set(pos.references) - set(source_map))
        party_coverage.append({
            "party_label": pos.party_label,
            "position_recorded": True,
            "references_supplied": pos.references,
            "unknown_references": missing,
            "position_terms": sorted(tokens(pos.position)),
            "review_note": "Position is recorded as supplied; it has not been independently verified.",
        })

    # Flag pairs with meaningful lexical overlap but different negation signals for human review.
    potential_conflicts = []
    for i, left in enumerate(req.sources):
        for right in req.sources[i + 1:]:
            common = tokens(left.text) & tokens(right.text)
            if len(common) >= 3:
                left_neg = bool(tokens(left.text) & _NEGATION)
                right_neg = bool(tokens(right.text) & _NEGATION)
                if left_neg != right_neg:
                    potential_conflicts.append({
                        "source_a": left.reference,
                        "source_b": right.reference,
                        "shared_terms": sorted(common)[:20],
                        "reason": "Potential language/negation difference detected; not a finding of contradiction.",
                        "requires_human_review": True,
                    })

    missing_issue_sources = [x["issue"] for x in issue_results if not x["source_found"]]
    unknown_citations = [
        {"claim_id": c["claim_id"], "references": c["unknown_references"]}
        for c in claim_results if c["unknown_references"]
    ]
    uncited_claims = [c["claim_id"] for c in claim_results if not c["cited_references"]]
    return {
        "status": "source_traceability_report_for_human_review",
        "case_number": req.case_number,
        "case_category": req.case_category,
        "synthetic_only": True,
        "no_outcome_predicted": True,
        "source_count": len(req.sources),
        "issue_count": len(req.issues),
        "claim_count": len(req.claims),
        "source_inventory": [
            {"reference": s.reference, "description": s.description, "page_or_location": s.page_or_location, "source_type": s.source_type, "characters": len(s.text)}
            for s in req.sources
        ],
        "issue_source_map": issue_results,
        "claim_traceability": claim_results,
        "party_position_coverage": party_coverage,
        "potential_conflicts_for_human_review": potential_conflicts,
        "completeness_flags": {
            "issues_without_candidate_source": missing_issue_sources,
            "claims_without_citations": uncited_claims,
            "claims_with_unknown_references": unknown_citations,
            "party_positions_recorded": len(req.party_positions),
            "parties_without_positions": [],
            "legal_authorities_verified": False,
        },
        "limitations": [
            "This is deterministic lexical analysis, not a legal AI model or legal advice.",
            "A word match does not prove a fact, support a proposition, authenticate a document, or establish admissibility.",
            "Potential conflicts are heuristic flags only; they may be false positives or miss real conflicts.",
            "The tool does not retrieve or verify statutes, regulations, precedents, amendments, or current law.",
            "The tool does not assess credibility, guilt, liability, damages, custody, bail, sentence, or the proper outcome.",
            "All original documents, translations, missing exhibits, objections, and arguments from every party must be reviewed by an authorised human.",
            "Synthetic records only; no real personal, confidential, or live court data may be submitted.",
        ],
        "human_review_required": True,
    }
